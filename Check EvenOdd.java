import java.util.Scanner;
public class Main {
  public static void main(string[] args) {
    Scanner sc = new Scanner(System.in);
    System.out.println("Enter number:");
    int n = sc.nextInt();
    if(n % 2 == 0) {
      System.out.println("Even");
    } else {
      System.out.println("Even");
    }
  }
}
      
